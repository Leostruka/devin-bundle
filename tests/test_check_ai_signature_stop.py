"""Stop-event behavior for check-ai-signature.py."""
import importlib.util
import json
import os
import subprocess
import sys
import threading
import time
from types import SimpleNamespace

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SCRIPT = os.path.join(ROOT, "scripts", "check-ai-signature.py")
GITSCAN = os.path.join(ROOT, "scripts", "_gitscan.py")
SIG_LINE = "Generated by " + "Chat" + "GPT"


def load_mod(name, path):
    spec = importlib.util.spec_from_file_location(name, path)
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return mod


def run_stop(cwd):
    env = os.environ.copy()
    env["DEVIN_PROJECT_DIR"] = str(cwd)
    return subprocess.run(
        [sys.executable, SCRIPT],
        input=json.dumps({"hook_event_name": "Stop", "stop_hook_active": False}),
        capture_output=True,
        text=True,
        encoding="utf-8",
        errors="replace",
        timeout=20,
        env=env,
    )


def git(cwd, *args):
    return subprocess.run(
        ["git", *args],
        cwd=cwd,
        capture_output=True,
        text=True,
        encoding="utf-8",
        errors="replace",
        timeout=10,
    )


def init_repo(tmp_path):
    assert git(tmp_path, "init").returncode == 0


def test_staged_signature_blocks(tmp_path):
    init_repo(tmp_path)
    (tmp_path / "note.md").write_text(SIG_LINE + "\n", encoding="utf-8")
    assert git(tmp_path, "add", "note.md").returncode == 0
    r = run_stop(tmp_path)
    assert r.returncode == 2
    assert "staged" in r.stdout


def test_unstaged_signature_blocks(tmp_path):
    init_repo(tmp_path)
    note = tmp_path / "note.md"
    note.write_text("plain\n", encoding="utf-8")
    assert git(tmp_path, "add", "note.md").returncode == 0
    note.write_text(SIG_LINE + "\n", encoding="utf-8")
    r = run_stop(tmp_path)
    assert r.returncode == 2
    assert "unstaged" in r.stdout


def test_clean_tree_allows_stop(tmp_path):
    init_repo(tmp_path)
    (tmp_path / "note.md").write_text("plain\n", encoding="utf-8")
    assert git(tmp_path, "add", "note.md").returncode == 0
    r = run_stop(tmp_path)
    assert r.returncode == 0, r.stdout + r.stderr


def test_gitscan_batch_overlaps_distinct_scans(monkeypatch):
    gitscan = load_mod("gitscan_under_test", GITSCAN)
    gitscan._cache.clear()
    lock = threading.Lock()
    active = 0
    max_active = 0

    def fake_run(argv, **kwargs):
        nonlocal active, max_active
        with lock:
            active += 1
            max_active = max(max_active, active)
        try:
            time.sleep(0.05)
            return SimpleNamespace(returncode=0, stdout="", stderr="")
        finally:
            with lock:
                active -= 1

    monkeypatch.setattr(gitscan.subprocess, "run", fake_run)
    scans = [
        ["git", "diff", "--cached", "--unified=0"],
        ["git", "diff", "--unified=0"],
        ["git", "rev-list", "@{u}..HEAD"],
        ["git", "ls-files", "--others", "--exclude-standard"],
    ]
    results = gitscan.run_git_batch(scans, cwd="repo")
    assert len(results) == 4
    assert all(getattr(r, "returncode", None) == 0 for r in results)
    assert max_active >= 3


def test_gitscan_batch_preserves_input_order_and_cache(monkeypatch):
    gitscan = load_mod("gitscan_order_under_test", GITSCAN)
    gitscan._cache.clear()
    calls = []

    def fake_run(argv, **kwargs):
        calls.append(list(argv))
        time.sleep(0.03 if "--cached" in argv else 0)
        return SimpleNamespace(
            returncode=0,
            stdout="cached" if "--cached" in argv else "plain",
            stderr="",
        )

    monkeypatch.setattr(gitscan.subprocess, "run", fake_run)
    scans = [
        ["git", "diff", "--cached", "--unified=0"],
        ["git", "diff", "--unified=0"],
    ]
    results = gitscan.run_git_batch(scans, cwd="repo")
    assert [r.stdout for r in results] == ["cached", "plain"]
    calls.clear()
    again = gitscan.run_git_batch(scans, cwd="repo")
    assert [r.stdout for r in again] == ["cached", "plain"]
    assert calls == []


def test_gitscan_batch_returns_per_scan_exceptions(monkeypatch):
    gitscan = load_mod("gitscan_exception_under_test", GITSCAN)
    gitscan._cache.clear()

    def fake_run(argv, **kwargs):
        if "rev-list" in argv:
            raise FileNotFoundError("git")
        return SimpleNamespace(returncode=0, stdout="", stderr="")

    monkeypatch.setattr(gitscan.subprocess, "run", fake_run)
    scans = [
        ["git", "diff", "--cached", "--unified=0"],
        ["git", "rev-list", "@{u}..HEAD"],
        ["git", "ls-files", "--others", "--exclude-standard"],
    ]
    results = gitscan.run_git_batch(scans, cwd="repo")
    assert getattr(results[0], "returncode", None) == 0
    assert isinstance(results[1], FileNotFoundError)
    assert getattr(results[2], "returncode", None) == 0
