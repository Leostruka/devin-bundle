"""Lazy regex compilation pins for rare hook gates."""
import importlib.util
import io
import json
import os
import re
import subprocess
import sys
from unittest.mock import patch

import pytest

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SCRIPTS = os.path.join(ROOT, "scripts")
sys.path.insert(0, SCRIPTS)
import _hookrun  # noqa: F401,E402  # preimport shared runner like production


def load_mod(name, script):
    spec = importlib.util.spec_from_file_location(
        name, os.path.join(SCRIPTS, script))
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return mod


def spy_compile(monkeypatch):
    calls = []
    real_compile = re.compile

    def spy(*args, **kwargs):
        calls.append(str(args[0]))
        return real_compile(*args, **kwargs)

    monkeypatch.setattr(re, "compile", spy)
    return calls


def payload(command):
    return {"hook_event_name": "PostToolUse", "tool_name": "exec",
            "tool_input": {"command": command},
            "tool_response": {"success": True, "output": "ok", "error": None}}


def test_dep_install_regex_not_compiled_for_benign_command(monkeypatch):
    calls = spy_compile(monkeypatch)
    gate = load_mod("dep_gate_lazy_test", "dep-audit-gate.py")
    install_compile = lambda p: "pip3?" in p and "scoop" in p
    assert not any(install_compile(p) for p in calls)
    calls.clear()
    with patch.object(sys, "stdin", io.StringIO(json.dumps(payload("git status")))):
        assert gate.main() == 0
    assert not any(install_compile(p) for p in calls)


def test_dep_install_regex_compiles_on_demand(monkeypatch):
    calls = spy_compile(monkeypatch)
    gate = load_mod("dep_gate_lazy_demand_test", "dep-audit-gate.py")
    calls.clear()
    with patch.object(sys, "stdin", io.StringIO(json.dumps(payload("pip install requests")))):
        assert gate.main() == 0
    assert any("pip3?" in p and "scoop" in p for p in calls)


def test_check_ai_signature_regexes_deferred(monkeypatch):
    calls = spy_compile(monkeypatch)
    load_mod("check_ai_lazy_test", "check-ai-signature.py")
    assert calls == []


def test_check_ai_signature_regexes_compile_on_demand(monkeypatch):
    calls = spy_compile(monkeypatch)
    gate = load_mod("check_ai_lazy_demand_test", "check-ai-signature.py")
    calls.clear()
    sig = "Generated by " + "Chat" + "GPT"
    data = {"hook_event_name": "PreToolUse", "tool_name": "write",
            "tool_input": {"file_path": "x.md", "content": sig}}
    with patch.object(sys, "stdin", io.StringIO(json.dumps(data))):
        with pytest.raises(SystemExit) as exc:
            gate.main()
    assert exc.value.code == 2
    assert any("Generated with" in p for p in calls)


def destructive_payload(command):
    return {"hook_event_name": "PreToolUse", "tool_name": "exec",
            "tool_input": {"command": command}}


def is_state_pattern(pattern):
    return len(pattern) > 5000 and "subagent-" in pattern


def test_destructive_state_regexes_not_compiled_for_benign_command(monkeypatch):
    calls = spy_compile(monkeypatch)
    gate = load_mod("destructive_lazy_test", "destructive-gate.py")
    assert not any(is_state_pattern(p) for p in calls)
    calls.clear()
    with patch.object(sys, "stdin", io.StringIO(json.dumps(destructive_payload("git status")))):
        with pytest.raises(SystemExit) as exc:
            gate.main()
    assert exc.value.code == 0
    assert not any(is_state_pattern(p) for p in calls)


def test_destructive_state_regex_compiles_on_demand(monkeypatch):
    calls = spy_compile(monkeypatch)
    gate = load_mod("destructive_lazy_demand_test", "destructive-gate.py")
    calls.clear()
    cmd = "rm state/subagent-x.json"
    with patch.object(sys, "stdin", io.StringIO(json.dumps(destructive_payload(cmd)))):
        with pytest.raises(SystemExit) as exc:
            gate.main()
    assert exc.value.code == 2
    assert any(is_state_pattern(p) for p in calls)


def run_destructive(command):
    return subprocess.run(
        [sys.executable, os.path.join(SCRIPTS, "destructive-gate.py")],
        input=json.dumps(destructive_payload(command)),
        capture_output=True,
        text=True,
        encoding="utf-8",
        errors="replace",
        timeout=15,
    )


def test_state_file_delete_still_blocks():
    r = run_destructive("rm state/subagent-x.json")
    assert r.returncode == 2
    assert "enforcement state" in r.stdout


def test_state_file_write_still_blocks():
    r = run_destructive("echo x > state/wtp-a.txt")
    assert r.returncode == 2
    assert "enforcement state" in r.stdout


def test_project_state_dir_remains_allowed():
    r = run_destructive("rm -rf src/state")
    assert r.returncode == 0, r.stdout + r.stderr
