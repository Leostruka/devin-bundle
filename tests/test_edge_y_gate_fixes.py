"""Tests for edge-audit gate fixes (issues 10, 26, 34, 42, 61-71).

Covers: check-push-green matcher/fail-closed/secrets/test-deletion,
check-ai-signature untracked scan, architecture-gate exec hatch removal,
render-user-hooks interpreter resolution, silent-error-review strong
errors, validate-tool-args profile deny, metrics sink.
"""
import importlib.util
import json
import os
import subprocess
import sys

import pytest

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SCRIPTS = os.path.join(ROOT, "scripts")
# Signature text assembled at runtime so this test file itself stays clean.
SIG_LINE = "Generated by " + "Chat" + "GPT"


def run_hook(script, payload, env_extra=None, timeout=20):
    env = os.environ.copy()
    env.update(env_extra or {})
    return subprocess.run(
        [sys.executable, os.path.join(SCRIPTS, script)],
        input=json.dumps(payload), capture_output=True, text=True,
        timeout=timeout, env=env,
    )


def push_payload(command):
    return {
        "hook_event_name": "PreToolUse",
        "tool_name": "exec",
        "tool_input": {"command": command},
    }


def load_mod(name, script):
    spec = importlib.util.spec_from_file_location(name, os.path.join(SCRIPTS, script))
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return mod


# --- issue 62: git push matcher ---

def test_push_matcher_plain():
    mod = load_mod("cpg", "check-push-green.py")
    assert mod.is_git_push("git push origin main")
    assert mod.is_git_push("git  push")
    assert mod.is_git_push("git\tpush")
    assert mod.is_git_push("git -C repo push")
    assert mod.is_git_push("git -c a=b push")
    assert mod.is_git_push("git --no-pager push")
    assert mod.is_git_push("echo ok && git push")
    assert mod.is_git_push("git -C /x log; git push")


def test_push_matcher_negative():
    mod = load_mod("cpg", "check-push-green.py")
    assert not mod.is_git_push("git status")
    assert not mod.is_git_push("git pull")
    assert not mod.is_git_push("git remote update")
    assert not mod.is_git_push('echo "git push"')
    assert not mod.is_git_push("vagrant status")


