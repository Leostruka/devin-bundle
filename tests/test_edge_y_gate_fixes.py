def test_metrics_sink_rotates(tmp_path, monkeypatch):
    """Issue #408: metrics.jsonl must not grow unbounded - emit_metric
    rotates at METRICS_MAX_BYTES keeping the newest half."""
    mod = load_mod("hookrun_rot", "_hookrun.py")
    monkeypatch.setenv("DEVIN_PROJECT_DIR", str(tmp_path))
    sink = tmp_path / ".devin" / "ledgers" / "metrics.jsonl"
    sink.parent.mkdir(parents=True)
    # prefill beyond the cap with parseable old lines
    old = ('{"t": 1, "event": "old", "pad": "'
           + "x" * 200 + '"}\n')
    sink.write_text(old * (mod.METRICS_MAX_BYTES // len(old) + 10),
                    encoding="utf-8")
    assert sink.stat().st_size > mod.METRICS_MAX_BYTES
    mod.emit_metric("probe", k=1)
    size = sink.stat().st_size
    assert size <= mod.METRICS_MAX_BYTES
    lines = sink.read_text(encoding="utf-8").splitlines()
    assert lines, "sink emptied by rotation"
    for ln in lines:
        json.loads(ln)  # every surviving line still parses
    assert json.loads(lines[-1])["event"] == "probe"


# --- issue 66: test deletion gate (Rule 25) ---

def _git_repo(tmp_path):
    subprocess.run(["git", "init"], cwd=tmp_path, capture_output=True)
    (tmp_path / "tests").mkdir()
    t = tmp_path / "tests" / "test_x.py"
    t.write_text("def test_x():\n    assert True\n")
    subprocess.run(["git", "add", "-A"], cwd=tmp_path, capture_output=True)
    subprocess.run(["git", "-c", "user.email=a@b", "-c", "user.name=t",
                    "commit", "-m", "init"], cwd=tmp_path, capture_output=True)
    return t


def test_deleted_test_file_blocks(tmp_path):
    t = _git_repo(tmp_path)
    t.unlink()
    r = run_hook("check-push-green.py", push_payload("git push"),
                 env_extra={"DEVIN_PROJECT_DIR": str(tmp_path)})
    assert r.returncode == 2
    assert "test" in r.stdout.lower()


def test_deleted_test_file_with_approval_ok(tmp_path):
    t = _git_repo(tmp_path)
    t.unlink()
    (tmp_path / ".devin").mkdir()
    (tmp_path / ".devin" / "test-deletion-approved").write_text(
        "approved removal: tests/test_x.py (superseded by test_y)")
    r = run_hook("check-push-green.py", push_payload("git push"),
                 env_extra={"DEVIN_PROJECT_DIR": str(tmp_path)})
    # approval naming the deleted file clears the deletion gate; tests/
    # exists but no framework marker, so the fail-closed framework check
    # blocks instead
    assert "test deletion" not in r.stdout


def test_deleted_test_file_approval_without_name_blocks(tmp_path):
    t = _git_repo(tmp_path)
    t.unlink()
    (tmp_path / ".devin").mkdir()
    (tmp_path / ".devin" / "test-deletion-approved").write_text("obsolete")
    r = run_hook("check-push-green.py", push_payload("git push"),
                 env_extra={"DEVIN_PROJECT_DIR": str(tmp_path)})
    # a marker that does not NAME the deleted test no longer approves it
    assert r.returncode == 2
    assert "test deletion" in r.stdout


def test_removed_test_def_approval_named_ok(tmp_path):
    t = _git_repo(tmp_path)
    # remove the def line from the tracked test file (uncommitted edit)
    t.write_text("")
