# --- issues 26/42: render-user-hooks interpreter ---

def test_render_hooks_resolves_interpreter(tmp_path):
    r = subprocess.run(
        [sys.executable, os.path.join(SCRIPTS, "render-user-hooks.py"),
         str(tmp_path)],
        capture_output=True, text=True, timeout=20)
    assert r.returncode == 0, r.stderr
    rendered = json.loads(r.stdout)
    for entries in rendered.values():
        for entry in entries:
            for h in entry["hooks"]:
                cmd = h.get("command", "")
                if not cmd:
                    continue
                assert "python scripts/" not in cmd
                interp = cmd.split('"')[1]
                assert os.path.isabs(interp), cmd


