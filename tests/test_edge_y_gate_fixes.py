# --- issue 34: per-profile deny ---

def _vta_env(tmp_path):
    return {"APPDATA": str(tmp_path), "XDG_CONFIG_HOME": str(tmp_path)}


def test_profile_recorded_on_dispatch(tmp_path):
    r = run_hook("validate-tool-args.py", {
        "hook_event_name": "PreToolUse",
        "tool_name": "run_subagent",
        "tool_input": {"task": "research x", "profile": "researcher"},
        "session_id": "sess-1",
    }, env_extra=_vta_env(tmp_path))
    assert r.returncode == 0
    state = tmp_path / "devin" / "state" / "subagent-sess-1.json"
    assert state.exists()
    assert json.loads(state.read_text())["profile"] == "researcher"


def test_profile_deny_requires_subagent_context(tmp_path):
    env = _vta_env(tmp_path)
    run_hook("validate-tool-args.py", {
        "hook_event_name": "PreToolUse",
        "tool_name": "run_subagent",
        "tool_input": {"task": "research x", "profile": "researcher"},
        "session_id": "sess-2",
    }, env_extra=env)
    # parent-context exec is NOT blocked (session_id is session-wide)
    r = run_hook("validate-tool-args.py", {
        "hook_event_name": "PreToolUse",
        "tool_name": "exec",
        "tool_input": {"command": "ls"},
        "session_id": "sess-2",
    }, env_extra=env)
    assert r.returncode == 0
    # subagent-context exec IS blocked for the denied profile
    r = run_hook("validate-tool-args.py", {
        "hook_event_name": "PreToolUse",
        "tool_name": "exec",
        "tool_input": {"command": "ls"},
        "session_id": "sess-2",
        "is_subagent": True,
    }, env_extra=env)
    assert r.returncode == 2


