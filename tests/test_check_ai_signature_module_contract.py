"""Module-level contract pins for check-ai-signature.py.

`.github/workflows/ci.yml` imports the hook as a module (`cas`) and scans
the tree with `cas.PATTERN` / `cas.ALLOWED_CONTEXTS`, expecting compiled
regex objects. C136 made compilation lazy inside functions and dropped the
module-level compiled attributes, breaking CI with
`AttributeError: module 'cas' has no attribute 'PATTERN'`
(run 45717276190, Static checks job).

These tests replicate the exact CI scan logic so the contract cannot
regress silently again. They must hold while import-time compilation stays
deferred (see tests/test_lazy_regex_compile.py).
"""
import importlib.util
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SCRIPTS = os.path.join(ROOT, "scripts")
sys.path.insert(0, SCRIPTS)
import _hookrun  # noqa: F401  # preimport shared runner like production


def load_cas():
    spec = importlib.util.spec_from_file_location(
        "cas", os.path.join(SCRIPTS, "check-ai-signature.py"))
    m = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(m)
    return m


def ci_scan(text, m):
    """Replicates the inline scan in .github/workflows/ci.yml verbatim."""
    hits = []
    for match in m.PATTERN.finditer(text):
        line_start = text.rfind("\n", 0, match.start()) + 1
        line_end = text.find("\n", match.end())
        line = text[line_start: line_end if line_end != -1 else len(text)]
        if any(a.search(line) for a in m.ALLOWED_CONTEXTS):
            continue
        hits.append(line)
        break
    return hits


def test_pattern_is_compiled_with_finditer():
    m = load_cas()
    assert hasattr(m.PATTERN, "finditer")
    assert hasattr(m.PATTERN, "search")


def test_allowed_contexts_are_compiled_patterns():
    m = load_cas()
    assert len(m.ALLOWED_CONTEXTS) > 0
    for ctx in m.ALLOWED_CONTEXTS:
        assert hasattr(ctx, "search"), "ALLOWED_CONTEXTS entries must be compiled"
        assert hasattr(ctx, "sub")


def test_identity_patterns_available_compiled():
    m = load_cas()
    assert hasattr(m.AI_IDENTITY, "search")
    assert len(m.IDENTITY_VALUE_PATTERNS) > 0
    for p in m.IDENTITY_VALUE_PATTERNS:
        assert hasattr(p, "finditer")


def test_ci_scan_flags_signature():
    m = load_cas()
    sig = "Generated by " + "Chat" + "GPT"
    assert ci_scan("some docs\n" + sig + "\nmore", m) != []


def test_ci_scan_allows_descriptive_context():
    m = load_cas()
    text = "This project uses AI-assisted tooling for review.\n"
    assert ci_scan(text, m) == []


def test_ci_scan_clean_text_passes():
    m = load_cas()
    assert ci_scan("ordinary documentation\nnothing here\n", m) == []
